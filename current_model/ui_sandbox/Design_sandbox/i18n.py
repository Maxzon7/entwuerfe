def t(key: str, lang: str = DEFAULT_LANGUAGE, **kwargs: Any) -> str:
    """
    Retrieves a localized UI string for `lang` (`"en"`, `"nl"`, `"es"`),
    falling back cleanly to English (`"en"`), and formats optional placeholders.
    """
    code = lang if lang in TRANSLATIONS else DEFAULT_LANGUAGE
    text = TRANSLATIONS[code].get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
